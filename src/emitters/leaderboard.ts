/**
 * free-llm-scout — Leaderboard Markdown Emitter
 * Human-readable ranking table for GitHub README / dashboard
 */

import { Emitter, ValidationResult, ModelInfo, EmitOptions } from '../types.js';
import { selectFleetModels, writeText } from '../utils.js';

export class LeaderboardEmitter implements Emitter {
  name = 'leaderboard';

  async emit(results: ValidationResult[], models: ModelInfo[], options: EmitOptions): Promise<string> {
    const modelMap = new Map(models.map(m => [m.id, m]));
    const resultMap = new Map(results.map(r => [`${r.provider}/${r.modelId}`, r]));

    const ranked = results
      .filter(r => r.passed)
      .sort((a, b) => b.score - a.score);

    const lines = [
      '# Free LLM Model Leaderboard',
      '',
      `> Auto-generated by [free-llm-scout](https://github.com/yiqizhuaboduan/free-llm-scout) at ${new Date().toISOString()}`,
      `> **Non-commercial free, commercial requires authorization (fanrujin2023@outlook.com)**`,
      '',
      '| Rank | Model | Provider | Score | Tool Calling | Structured Output | Context | Quota | Latency |',
      '|------|-------|----------|-------|--------------|-------------------|---------|-------|---------|',
    ];

    for (let i = 0; i < ranked.length; i++) {
      const r = ranked[i];
      const m = modelMap.get(`${r.provider}/${r.modelId}`);
      const toolCalling = this.getCheckScore(r, 'tool-calling');
      const structured = this.getCheckScore(r, 'structured-output');
      const context = m?.contextWindow.toLocaleString() ?? 'N/A';
      const quota = m?.quota?.kind ?? 'durable';
      const latency = `${r.checks.find(c => c.name === 'rate-limit')?.latencyMs ?? 'N/A'}ms`;

      lines.push(`| ${i + 1} | ${m?.name ?? r.modelId} | ${r.provider} | ${r.score} | ${toolCalling} | ${structured} | ${context} | ${quota} | ${latency} |`);
    }

    lines.push('');
    lines.push('---');
    lines.push('');
    lines.push('## Fleet Recommendation (DSH `model-fleet` chain)');
    lines.push('');

    const fleetModels = selectFleetModels(results, models, {
      minScore: options.minScore ?? 60,
      maxFleetSize: options.maxFleetSize ?? 15,
      providerPriority: options.providerPriority ?? ['openrouter', 'siliconflow', 'modelscope', 'bailian', 'zhipu', 'deepseek-account'],
    });

    for (const m of fleetModels) {
      const r = resultMap.get(m.id);
      lines.push(`- \`${m.provider}/${m.modelId}\` — Score: ${r?.score ?? 'N/A'}, Context: ${m.contextWindow.toLocaleString()}`);
    }

    const mdContent = lines.join('\n');
    const outFile = `${options.outDir}/LEADERBOARD.md`;
    writeText(outFile, mdContent);

    return `Generated leaderboard with ${ranked.length} ranked models → ${outFile}`;
  }

  private getCheckScore(result: ValidationResult, checkName: string): string {
    const check = result.checks.find(c => c.name === checkName);
    if (!check) return 'N/A';
    return check.passed ? `✅ ${check.score}` : `❌ ${check.score}`;
  }
}